// Дешёвые фильтры «не-ИТ» (используются до скачивания PDF и в Pre-Filter)
const RE_IT_CABINET = /(?:шкаф[а-я]*[ \t]+(?:серверн|телекоммуникац|коммутацион|сетев|настенн[а-я]*[ \t]+телекоммуникац)[а-я]*|(?:серверн|телекоммуникацион|коммутацион)[а-я]*[ \t]+шкаф[а-я]*)/gi;
const RE_NON_IT_LOT = /(?:мебель[а-я]*|спальн[а-я]*|кухонн[а-я]*|кроват[а-я]*|шкаф[а-я]*|диван[а-я]*|матрас[а-я]*|одежд[а-я]*|посуд[а-я]*|клеточн[а-я]*\s*культур|зажим[а-я]*\s*для\s*бумаг|папка-планшет|планшет\s*канцелярск|дезинфекционн[а-я]*|морозильн[а-я]*|холодильн[а-я]*|автомобильн[а-я]*|велосипедн[а-я]*|камера[ \t]+хранения)/i;
function tsIsNonItText(text) {
  const t = String(text || '').replace(RE_IT_CABINET, ' ');
  return RE_NON_IT_LOT.test(t);
}
